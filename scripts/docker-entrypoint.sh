#!/bin/bash
# ============================================================
# InfoGet Docker 容器入口脚本
# ============================================================
# 功能:
#   1. 启动 cron 守护进程（用于定时更新 RSS）
#   2. 执行 CMD 指定的命令（默认是启动 HTTP 服务器）
#
# 容器启动后会自动:
#   - 每 6 小时快速爬取一次博客文章
#   - 每天凌晨 3 点完整爬取（访问详情页）
#   - 每周日凌晨 2 点输出统计信息
# ============================================================

set -e

# 启动 cron 后台运行
echo "[入口] 启动 cron 定时任务..."
cron

echo "[入口] 定时任务已配置，即将启动主进程..."
echo "[入口] 查看 cron 日志: docker logs <容器名> | grep CRON"
echo "[入口] 查看定时任务: docker exec <容器名> crontab -l"
echo "[入口] 手动触发更新: docker exec <容器名> bash scripts/update_feed.sh"
echo ""

# 执行传入的命令（通常是启动 HTTP 服务器）
exec "$@"
